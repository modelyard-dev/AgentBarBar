import { expect, test, type Page } from '@playwright/test'
import path from 'node:path'

async function openControls(page: Page) {
  if (new URL(page.url()).pathname === '/settings') await expect(page.locator('.settings-stack')).toBeVisible()
  for (const selector of ['.filter-disclosure', '.advanced-tools', '.utility-menu']) {
    const details = page.locator(selector)
    if (await details.count() && !(await details.getAttribute('open') !== null)) await details.locator(':scope > summary').click()
  }
}

