  await page.reload()
  await openControls(page)
  await page.locator('.collector-row').filter({ hasText: 'codex-local' }).locator('.connection-details > summary').click()
  await expect(page.locator('.collector-row').filter({ hasText: 'codex-local' })).toContainText('Survey results')
