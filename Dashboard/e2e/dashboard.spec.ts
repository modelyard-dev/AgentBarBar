test('reload paints the exact cached filter while revalidation is delayed', async ({ page }) => {
  await page.goto('/overview?range=all')
  await openControls(page)
  const value = await page.locator('.primary-stat').innerText()
  await expect(page.locator('.primary-stat')).toContainText('126.9K')
  await page.route('**/api/overview?**', async route => { await new Promise(resolve => setTimeout(resolve, 1800)); await route.continue() })
  await page.reload({ waitUntil: 'domcontentloaded' })
  await openControls(page)
  await expect(page.locator('.primary-stat')).toContainText('126.9K', { timeout: 800 })
  await expect(page.locator('.loading-state')).toHaveCount(0)
  await expect(page.locator('.cache-status')).toContainText(/background|后台/)
  expect(value).toContain('126.9K')
  await page.unroute('**/api/overview?**')
})

